create or replace view public.line_monthly_usage
with (security_invoker = true)
as
select
  date_trunc('month', sent_at) as month,
  count(*) filter (where direction = 'outbound') as outbound_log_rows,
  coalesce(sum(billing_units) filter (where direction = 'outbound'), 0)::bigint as billing_units,
  count(*) filter (where direction = 'outbound' and delivery_mode = 'reply') as reply_rows,
  count(*) filter (where direction = 'outbound' and delivery_mode in ('push','multicast','broadcast','narrowcast')) as proactive_rows,
  coalesce(sum(message_object_count) filter (where direction = 'outbound'), 0)::bigint as message_objects
from public.line_message_log
group by 1;

