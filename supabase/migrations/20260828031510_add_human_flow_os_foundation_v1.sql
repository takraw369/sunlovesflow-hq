create table if not exists public.person_serials (
  person_id uuid primary key references public.contacts(id) on delete cascade,
  serial_no bigint generated by default as identity unique,
  serial_code text generated always as ('SLF-' || lpad(serial_no::text, 6, '0')) stored unique,
  created_at timestamptz not null default now()
);

alter table public.person_serials enable row level security;

insert into public.person_serials (person_id)
select c.id from public.contacts c
on conflict (person_id) do nothing;

create or replace function public.ensure_person_serial()
returns trigger
language plpgsql
security definer
set search_path = public, pg_temp
as $$
begin
  insert into public.person_serials(person_id) values (new.id)
  on conflict (person_id) do nothing;
  return new;
end;
$$;

drop trigger if exists trg_contacts_ensure_person_serial on public.contacts;
create trigger trg_contacts_ensure_person_serial
after insert on public.contacts
for each row execute function public.ensure_person_serial();

